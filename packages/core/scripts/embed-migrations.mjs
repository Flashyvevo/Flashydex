// Embeds the two SQL migration chains into a TS module so core stays bundler/runtime agnostic (no fs, no import.meta.glob).
// Run after `drizzle-kit generate`; test/migrator.test.ts fails if the generated module drifts from the .sql files.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const root = new URL('../', import.meta.url);
const read = (chain) => {
  const dir = new URL(`migrations/${chain}/`, root);
  return readdirSync(dir)
    .filter((f) => f.endsWith('.sql'))
    .sort()
    .map((f) => ({ version: f.replace(/\.sql$/, ''), sql: readFileSync(new URL(f, dir), 'utf8').replace(/\r\n/g, '\n') }));
};
const out = [
  '// GENERATED by scripts/embed-migrations.mjs from migrations/{user,catalog}/*.sql - do not edit.',
  "import type { MigrationFile } from './migrator';",
  '',
  `export const USER_MIGRATIONS: readonly MigrationFile[] = ${JSON.stringify(read('user'), null, 2)};`,
  '',
  `export const CATALOG_MIGRATIONS: readonly MigrationFile[] = ${JSON.stringify(read('catalog'), null, 2)};`,
  ''
].join('\n');
writeFileSync(fileURLToPath(new URL('src/db/migrations.generated.ts', root)), out);
console.log('embedded migrations');
