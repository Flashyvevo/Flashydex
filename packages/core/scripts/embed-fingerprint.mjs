// Generates src/db/catalog-fingerprint.generated.ts: the exact sqlite_master object list produced by the bundled catalog migrations.
// R09: core compares every candidate/active catalog against this list (object allowlist + normalized SQL), not just meta/counts.
// Run via `npm run db:embed`; test/candidate-validation.test.ts fails when the generated module drifts from migrations/catalog/*.sql.
import { createHash } from 'node:crypto';
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import Database from 'better-sqlite3';

const root = new URL('../', import.meta.url);
const dir = new URL('migrations/catalog/', root);
const files = readdirSync(dir).filter((f) => f.endsWith('.sql')).sort();
const db = new Database(':memory:');
for (const f of files) {
  const sql = readFileSync(new URL(f, dir), 'utf8').replace(/\r\n/g, '\n');
  for (const stmt of sql.split('--> statement-breakpoint').map((s) => s.trim()).filter(Boolean)) db.exec(stmt);
}
const normalize = (s) => s.replace(/\s+/g, ' ').trim();
const objects = db
  .prepare("SELECT type, name, tbl_name AS tbl, sql FROM sqlite_master WHERE name NOT LIKE 'sqlite\\_%' ESCAPE '\\' ORDER BY type, name")
  .all()
  .map((r) => ({ type: r.type, name: r.name, table: r.tbl, sql: r.sql === null ? null : normalize(r.sql) }));
const fingerprint = createHash('sha256').update(JSON.stringify(objects)).digest('hex');
const out = [
  '// GENERATED by scripts/embed-fingerprint.mjs from migrations/catalog/*.sql - do not edit.',
  'export type SchemaObject = { readonly type: string; readonly name: string; readonly table: string; readonly sql: string | null };',
  '',
  `export const CATALOG_SCHEMA_OBJECTS: readonly SchemaObject[] = ${JSON.stringify(objects, null, 2)};`,
  '',
  `export const CATALOG_SCHEMA_FINGERPRINT = ${JSON.stringify(fingerprint)};`,
  ''
].join('\n');
writeFileSync(fileURLToPath(new URL('src/db/catalog-fingerprint.generated.ts', root)), out);
console.log('embedded catalog fingerprint', fingerprint.slice(0, 12), objects.length, 'objects');
